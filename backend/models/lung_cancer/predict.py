"""Lung Cancer Risk-Screening Inference Interface.

Provides a standalone, stateless prediction interface that loads the serialized
preprocessor and model artifacts, validates input against the feature schema,
and returns risk screening predictions and calibrated probabilities.
"""

import json
import os
from typing import Any, Dict, List, Optional, Union
import joblib
import numpy as np
import pandas as pd

from preprocessing import (
    FEATURE_COLUMNS,
    format_single_input,
)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "model.joblib")
PREPROCESSOR_PATH = os.path.join(BASE_DIR, "preprocessor.joblib")
SCHEMA_PATH = os.path.join(BASE_DIR, "feature_schema.json")

# Module-level cached artifacts
_MODEL = None
_PREPROCESSOR = None
_SCHEMA = None


def get_artifacts():
    """Load model, preprocessor, and schema lazily with caching."""
    global _MODEL, _PREPROCESSOR, _SCHEMA
    if _MODEL is None:
        if not os.path.exists(MODEL_PATH):
            raise FileNotFoundError(f"Model artifact not found at: {MODEL_PATH}. Train model first.")
        _MODEL = joblib.load(MODEL_PATH)
        
    if _PREPROCESSOR is None:
        if not os.path.exists(PREPROCESSOR_PATH):
            raise FileNotFoundError(f"Preprocessor artifact not found at: {PREPROCESSOR_PATH}.")
        _PREPROCESSOR = joblib.load(PREPROCESSOR_PATH)
        
    if _SCHEMA is None:
        if os.path.exists(SCHEMA_PATH):
            with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
                _SCHEMA = json.load(f)
                
    return _MODEL, _PREPROCESSOR, _SCHEMA


def compute_risk_level(probability: float) -> str:
    """Categorize screening probability into an interpretable software risk tier.

    NOTE: The tiers ('Low', 'Moderate', 'High') are software categorization rules
    based on model predicted probabilities (<0.35 = Low, 0.35-0.70 = Moderate,
    >=0.70 = High). They are intended solely for UI display and heuristic screening
    stratification, and are NOT clinically or medically validated diagnostic thresholds.
    """
    if probability < 0.35:
        return "Low"
    elif probability < 0.70:
        return "Moderate"
    else:
        return "High"


def predict(input_data: Union[Dict[str, Any], pd.DataFrame, List[Dict[str, Any]]]) -> Union[Dict[str, Any], List[Dict[str, Any]]]:
    """Generate risk screening prediction and confidence probability.
    
    Args:
        input_data: Single patient feature dictionary, DataFrame, or list of feature dicts.
        
    Returns:
        Dictionary (or list of dicts) with:
            - prediction (str): 'YES' or 'NO'
            - class (int): 1 or 0
            - probability (float): Model estimated probability for positive class [0.0, 1.0]
            - risk_level (str): 'Low', 'Moderate', or 'High'
            - disclaimer (str): Clinical notice that this is a screening tool, not a diagnosis.
            
    Raises:
        ValueError: If input features are missing, invalid, or out of range.
        FileNotFoundError: If model artifacts are missing.
    """
    model, preprocessor, _ = get_artifacts()
    
    # Handle list of dictionaries
    if isinstance(input_data, list):
        return [predict(item) for item in input_data]
        
    # Handle single dictionary input
    if isinstance(input_data, dict):
        df_input = format_single_input(input_data)
        
        # Transform through fitted preprocessor
        X_proc = preprocessor.transform(df_input)
        
        # Predict class and probability
        pred_class = int(model.predict(X_proc)[0])
        probabilities = model.predict_proba(X_proc)[0]
        pos_prob = float(probabilities[1])
        
        return {
            "prediction": "YES" if pred_class == 1 else "NO",
            "class": pred_class,
            "probability": round(pos_prob, 4),
            "risk_level": compute_risk_level(pos_prob),
            "disclaimer": "This prediction is generated by a statistical screening model and does NOT constitute a clinical diagnosis. Consult a pulmonologist for medical evaluation.",
        }
        
    # Handle DataFrame input
    if isinstance(input_data, pd.DataFrame):
        results = []
        for _, row in input_data.iterrows():
            results.append(predict(row.to_dict()))
        return results
        
    raise ValueError(f"Unsupported input type: {type(input_data)}. Expected dict, list of dicts, or pandas DataFrame.")


